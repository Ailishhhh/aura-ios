// Folds assets/lyrics (the page Android shows in a WebView, am-lyrics and its font) into one HTML
// string at src/lyrics/page.generated.ts, so the iPhone's WebView needs no files.
// Run after changing anything in assets/lyrics: node scripts/embed-lyrics.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../assets/lyrics/", import.meta.url);
let html = readFileSync(new URL("index.html", dir), "utf8");
const script = readFileSync(new URL("am-lyrics.js", dir), "utf8");
const font = readFileSync(new URL("instrument_serif.ttf", dir)).toString("base64");

if (script.includes("</script")) throw new Error("am-lyrics.js contains </script and can't be inlined");

html = html
  .replace("url('instrument_serif.ttf')", `url(data:font/ttf;base64,${font})`)
  .replace('<script type="module" src="am-lyrics.js"></script>', () => `<script type="module">${script}</script>`)
  // The Android page talks to Kotlin through AuraBridge; here it posts to React Native.
  .replace(
    "<script type=\"module\">\n  const el",
    `<script>
  window.AuraBridge = {
    ready: () => window.ReactNativeWebView.postMessage(JSON.stringify({ type: "ready" })),
    seek: (ms) => window.ReactNativeWebView.postMessage(JSON.stringify({ type: "seek", ms })),
  };
</script>
<script type="module">
  const el`,
  );

if (!html.includes("ReactNativeWebView")) throw new Error("Couldn't add the bridge to the lyrics page");

writeFileSync(
  new URL("../src/lyrics/page.generated.ts", import.meta.url),
  `// Generated by scripts/embed-lyrics.mjs from assets/lyrics. Don't edit by hand.\n` +
    `// Contains am-lyrics (MPL-2.0, https://github.com/binimum/am-lyrics), unmodified.\n` +
    `export const LYRICS_PAGE = ${JSON.stringify(html)};\n`,
);
console.log(`Lyrics page: ${(html.length / 1024).toFixed(0)} KB`);
